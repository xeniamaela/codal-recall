// Generates supabase/seed.sql from the built-in starter set plus any JSON files in ./codals/.
// Each JSON file: { "id": "labor", "name": "Labor Code of the Philippines", "short": "Labor Code",
//                   "law": "P.D. No. 442", "provisions": [ { "label": "Art. 1", "heading": "...", "text": "..." } ] }
// Tip: import a full codal in the app (Import tab), then use "Export JSON" under "Your imports".
//
// Usage: node scripts/make-seed-sql.mjs   ->   paste supabase/seed.sql into the Supabase SQL Editor.
import fs from 'node:fs';
import path from 'node:path';
import { SEED_CODES } from '../src/data/seed.js';
import { slug } from '../src/lib/text.js';

const q = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

const codes = new Map(SEED_CODES.map((c) => [c.id, structuredClone(c)]));
const dir = path.resolve('codals');
if (fs.existsSync(dir)) {
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json'))) {
    const c = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    const prev = codes.get(c.id);
    const byLabel = new Map((prev?.provisions || []).map((p) => [p.label, p]));
    for (const p of c.provisions) byLabel.set(p.label, p);
    codes.set(c.id, { ...prev, ...c, provisions: [...byLabel.values()] });
    console.log(`+ ${f}: ${c.provisions.length} provisions`);
  }
}

let sql = '-- Generated by scripts/make-seed-sql.mjs\nbegin;\n';
for (const c of codes.values()) {
  sql += `insert into public.codes (id, name, short, law) values (${q(c.id)}, ${q(c.name)}, ${q(c.short)}, ${q(c.law)})\n` +
    `  on conflict (id) do update set name = excluded.name, short = excluded.short, law = excluded.law;\n`;
  c.provisions.forEach((p, i) => {
    sql += `insert into public.provisions (id, code_id, label, heading, text, note, sort) values (` +
      `${q(`${c.id}:${slug(p.label)}`)}, ${q(c.id)}, ${q(p.label)}, ${q(p.heading)}, ${q(p.text)}, ${q(p.note)}, ${i})\n` +
      `  on conflict (id) do update set heading = excluded.heading, text = excluded.text, note = excluded.note, sort = excluded.sort, updated_at = now();\n`;
  });
}
sql += 'commit;\n';
fs.mkdirSync('supabase', { recursive: true });
fs.writeFileSync('supabase/seed.sql', sql);
console.log(`Wrote supabase/seed.sql (${[...codes.values()].reduce((n, c) => n + c.provisions.length, 0)} provisions)`);
